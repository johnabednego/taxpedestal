/**
 * Translation catalogues.
 *
 * ============================================================================
 * SCOPE, STATED HONESTLY
 * ============================================================================
 * These cover the languages spoken as an official or majority language across
 * the large majority of the world's population and a substantial share of its
 * countries. They are NOT every language of every country, and claiming
 * otherwise would mean machine-translating financial and legal terminology into
 * languages nobody on the team can check — shipping confident-sounding errors
 * into a product that handles money.
 *
 * Adding a language is a file drop: add an entry here, and it appears in the
 * switcher with its coverage percentage. No component changes.
 *
 * BEFORE COMMERCIAL LAUNCH these need review by native speakers with accounting
 * vocabulary. "Invoice", "receipt", "bill" and "statement" are distinct legal
 * terms in several of these languages, and a plausible mistranslation on a tax
 * document is worse than leaving it in English. The coverage figure in the UI
 * exists so this is visible rather than assumed.
 */

