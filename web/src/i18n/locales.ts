/** Every literal key present in the English catalogue. */
type CatalogKey = keyof typeof en

/** CLDR plural categories. Arabic uses all six; English uses two. */
type PluralCategory = 'zero' | 'one' | 'two' | 'few' | 'many' | 'other'

/**
 * The base of a plural family: `dash.openInvoices_one` yields
 * `dash.openInvoices`, which is what callers actually pass to `t`.
 */
type PluralBase<K> = K extends `${infer Base}_${PluralCategory}` ? Base : never

/**
 * What `t()` accepts: every literal key, plus the base of every plural family.
 * Declaring the base this way means `t('dash.openInvoices', { count })` type
 * checks without the base needing its own redundant catalogue entry.
 */
export type TranslationKey = CatalogKey | PluralBase<CatalogKey>

type Catalog = Partial<Record<CatalogKey, string>>

